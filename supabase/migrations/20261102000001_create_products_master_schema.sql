-- 9. 一括コピー後の IDENTITY シーケンス同期用 RPC 関数
-- ============================================================================
CREATE OR REPLACE FUNCTION public.sync_products_row_seq()
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  max_seq BIGINT;
BEGIN
  SELECT COALESCE(MAX(row_seq), 0) INTO max_seq FROM public.products;
  IF max_seq > 0 THEN
    PERFORM setval(pg_get_serial_sequence('public.products', 'row_seq'), max_seq, true);
  END IF;
  RETURN max_seq;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_products_row_seq() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sync_products_row_seq() TO service_role;

