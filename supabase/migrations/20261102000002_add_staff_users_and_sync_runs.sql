-- =============================================================================
-- B.I.S EC Phase 1 Security & Sync Hardening Migration
-- 1. public.staff_users: Allowlist of authorized B.I.S staff accounts
-- 2. public.product_sync_runs: Audit & status log for periodic Sheets->Supabase diff sync
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.staff_users (
  email TEXT PRIMARY KEY CHECK (email = lower(btrim(email)) AND email <> ''),
  is_active BOOLEAN NOT NULL DEFAULT true,
  note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_staff_users_set_updated_at ON public.staff_users;
CREATE TRIGGER trg_staff_users_set_updated_at
  BEFORE UPDATE ON public.staff_users
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at_timestamp();

CREATE TABLE IF NOT EXISTS public.product_sync_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  trigger_source TEXT NOT NULL DEFAULT 'scheduled',
  status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
  sheets_count INTEGER,
  supabase_before_count INTEGER,
  upserted_count INTEGER NOT NULL DEFAULT 0,
  deleted_count INTEGER NOT NULL DEFAULT 0,
  rolling_checked_count INTEGER NOT NULL DEFAULT 0,
  changed_product_ids TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  deleted_product_ids TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  error_message TEXT
);

CREATE INDEX IF NOT EXISTS idx_product_sync_runs_started_at
  ON public.product_sync_runs (started_at DESC);

ALTER TABLE public.staff_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_sync_runs ENABLE ROW LEVEL SECURITY;
